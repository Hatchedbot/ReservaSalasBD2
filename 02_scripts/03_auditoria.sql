--  Proyecto : Sistema de Reserva de Salas Universitario  (LM_RESERVASALAS)
--  Script   : 03_auditoria.sql
--  Ejecutar : conectado como LM_RESERVASALAS, despues de 01 y 02
--
--  Solucion de auditoria:
--   1. Tabla AUDITORIA: guarda CUANDO (fecha), QUIEN (usuario de BD,
--      usuario de la aplicacion, usuario del S.O., equipo, IP, programa),
--      QUE tabla y operacion (INSERT/UPDATE/DELETE), la llave del registro,
--      y los datos ANTERIORES y NUEVOS en formato JSON.
--   2. Paquete PL/SQL PKG_AUDITORIA:
--        - REGISTRAR       : inserta una fila en AUDITORIA.
--        - GENERAR_TRIGGER : lee el diccionario de Oracle (USER_TAB_COLUMNS
--                            y USER_CONSTRAINTS) y crea automaticamente
--                            el trigger TRG_AUD_<TABLA> para una tabla.
--        - GENERAR_TODOS   : crea los triggers para TODAS las tablas del
--                            esquema (excepto AUDITORIA). Si se agrega una
--                            tabla o columna, basta con volver a ejecutarlo.
--        - PURGAR          : unica forma permitida de borrar auditoria antigua.
--   3. Trigger TRG_AUDITORIA_PROTEGER: impide modificar o borrar registros
--      de auditoria (integridad del historial).
-- =====================================================================
SET ECHO ON
SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR CONTINUE
DROP TABLE AUDITORIA CASCADE CONSTRAINTS PURGE;
WHENEVER SQLERROR EXIT SQL.SQLCODE

-- ---------------------------------------------------------------------
-- 1. Tabla de auditoria
-- ---------------------------------------------------------------------
CREATE TABLE AUDITORIA (
  ID_AUDITORIA          NUMBER(12)     GENERATED BY DEFAULT AS IDENTITY,
  FECHA                 TIMESTAMP(3)   DEFAULT SYSTIMESTAMP NOT NULL,
  TABLA                 VARCHAR2(30)   NOT NULL,
  OPERACION             VARCHAR2(6)    NOT NULL,
  ID_REGISTRO           VARCHAR2(100)  NOT NULL,
  USUARIO_BD            VARCHAR2(128)  DEFAULT USER NOT NULL,
  USUARIO_APP           VARCHAR2(128),
  USUARIO_SO            VARCHAR2(128),
  EQUIPO                VARCHAR2(128),
  IP                    VARCHAR2(45),
  PROGRAMA              VARCHAR2(128),
  COLUMNAS_MODIFICADAS  VARCHAR2(1000),
  DATOS_ANTERIORES      CLOB,
  DATOS_NUEVOS          CLOB,
  CONSTRAINT PK_AUDITORIA           PRIMARY KEY (ID_AUDITORIA),
  CONSTRAINT CK_AUDITORIA_OPERACION CHECK (OPERACION IN ('INSERT','UPDATE','DELETE')),
  CONSTRAINT CK_AUDITORIA_JSON_ANT  CHECK (DATOS_ANTERIORES IS JSON),
  CONSTRAINT CK_AUDITORIA_JSON_NUE  CHECK (DATOS_NUEVOS IS JSON)
);
CREATE INDEX IX_AUDITORIA_FECHA ON AUDITORIA (FECHA);
CREATE INDEX IX_AUDITORIA_TABLA ON AUDITORIA (TABLA, OPERACION);

COMMENT ON TABLE AUDITORIA IS 'Historial de cambios (INSERT, UPDATE, DELETE) de todas las tablas del esquema';
COMMENT ON COLUMN AUDITORIA.ID_AUDITORIA         IS 'Identificador unico del evento de auditoria (autoincremental)';
COMMENT ON COLUMN AUDITORIA.FECHA                IS 'Fecha y hora exacta (milisegundos) del cambio';
COMMENT ON COLUMN AUDITORIA.TABLA                IS 'Tabla afectada';
COMMENT ON COLUMN AUDITORIA.OPERACION            IS 'INSERT, UPDATE o DELETE';
COMMENT ON COLUMN AUDITORIA.ID_REGISTRO          IS 'Valor de la llave primaria del registro afectado (compuesta separada por guion)';
COMMENT ON COLUMN AUDITORIA.USUARIO_BD           IS 'Usuario de base de datos que ejecuto el cambio';
COMMENT ON COLUMN AUDITORIA.USUARIO_APP          IS 'Usuario de la aplicacion web (CLIENT_IDENTIFIER de la sesion)';
COMMENT ON COLUMN AUDITORIA.USUARIO_SO           IS 'Usuario del sistema operativo del cliente';
COMMENT ON COLUMN AUDITORIA.EQUIPO               IS 'Nombre del equipo cliente';
COMMENT ON COLUMN AUDITORIA.IP                   IS 'Direccion IP del cliente';
COMMENT ON COLUMN AUDITORIA.PROGRAMA             IS 'Programa o modulo cliente (SQL*Plus, app web, etc.)';
COMMENT ON COLUMN AUDITORIA.COLUMNAS_MODIFICADAS IS 'En UPDATE: lista de columnas cuyo valor cambio';
COMMENT ON COLUMN AUDITORIA.DATOS_ANTERIORES     IS 'JSON con el registro antes del cambio (UPDATE y DELETE)';
COMMENT ON COLUMN AUDITORIA.DATOS_NUEVOS         IS 'JSON con el registro despues del cambio (INSERT y UPDATE)';

-- ---------------------------------------------------------------------
-- 2. Paquete de auditoria
-- ---------------------------------------------------------------------
CREATE OR REPLACE PACKAGE PKG_AUDITORIA AS
  -- Bandera interna: solo PURGAR puede borrar registros de auditoria
  g_permitir_purga BOOLEAN := FALSE;

  PROCEDURE REGISTRAR (
    p_tabla     IN VARCHAR2,
    p_operacion IN VARCHAR2,
    p_id        IN VARCHAR2,
    p_columnas  IN VARCHAR2,
    p_anterior  IN CLOB,
    p_nuevo     IN CLOB);

  FUNCTION  TEXTO_TRIGGER  (p_tabla IN VARCHAR2) RETURN CLOB;
  PROCEDURE GENERAR_TRIGGER(p_tabla IN VARCHAR2);
  PROCEDURE GENERAR_TODOS;
  PROCEDURE PURGAR(p_antes_de IN DATE);
END PKG_AUDITORIA;
/

CREATE OR REPLACE PACKAGE BODY PKG_AUDITORIA AS

  -- Inserta el evento. Se ejecuta en la MISMA transaccion del cambio:
  -- si el cambio se deshace (ROLLBACK) su auditoria tambien.
  PROCEDURE REGISTRAR (
    p_tabla     IN VARCHAR2,
    p_operacion IN VARCHAR2,
    p_id        IN VARCHAR2,
    p_columnas  IN VARCHAR2,
    p_anterior  IN CLOB,
    p_nuevo     IN CLOB) IS
  BEGIN
    INSERT INTO AUDITORIA (FECHA, TABLA, OPERACION, ID_REGISTRO, USUARIO_BD,
                           USUARIO_APP, USUARIO_SO, EQUIPO, IP, PROGRAMA,
                           COLUMNAS_MODIFICADAS, DATOS_ANTERIORES, DATOS_NUEVOS)
    VALUES (SYSTIMESTAMP, p_tabla, p_operacion, p_id, USER,
            SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'),
            SYS_CONTEXT('USERENV','OS_USER'),
            SYS_CONTEXT('USERENV','HOST'),
            SYS_CONTEXT('USERENV','IP_ADDRESS'),
            NVL(SYS_CONTEXT('USERENV','MODULE'), SYS_CONTEXT('USERENV','CLIENT_PROGRAM_NAME')),
            RTRIM(p_columnas, ','), p_anterior, p_nuevo);
  END REGISTRAR;

  -- Construye el codigo fuente del trigger de auditoria de una tabla,
  -- leyendo sus columnas y su llave primaria desde el diccionario.
  FUNCTION TEXTO_TRIGGER (p_tabla IN VARCHAR2) RETURN CLOB IS
    v_tabla  VARCHAR2(128) := UPPER(p_tabla);
    v_old    VARCHAR2(32767);
    v_new    VARCHAR2(32767);
    v_cmp    VARCHAR2(32767);
    v_idold  VARCHAR2(4000);
    v_idnew  VARCHAR2(4000);
    v_sql    CLOB;
    NL       CONSTANT VARCHAR2(1) := CHR(10);
  BEGIN
    FOR c IN (SELECT COLUMN_NAME, DATA_TYPE
                FROM USER_TAB_COLUMNS
               WHERE TABLE_NAME = v_tabla
               ORDER BY COLUMN_ID) LOOP
      v_old := v_old || CASE WHEN v_old IS NOT NULL THEN ', ' END
               || '''' || c.COLUMN_NAME || ''' VALUE :OLD.' || c.COLUMN_NAME;
      v_new := v_new || CASE WHEN v_new IS NOT NULL THEN ', ' END
               || '''' || c.COLUMN_NAME || ''' VALUE :NEW.' || c.COLUMN_NAME;
      -- Deteccion de columnas cuyo valor realmente cambio. Se tratan los NULL
      -- explicitamente porque NULL <> valor no es verdadero en SQL.
      IF c.DATA_TYPE NOT IN ('CLOB','BLOB','NCLOB','LONG') THEN
        v_cmp := v_cmp || '    IF (:OLD.' || c.COLUMN_NAME || ' <> :NEW.' || c.COLUMN_NAME || ')'
                 || ' OR (:OLD.' || c.COLUMN_NAME || ' IS NULL AND :NEW.' || c.COLUMN_NAME || ' IS NOT NULL)'
                 || ' OR (:OLD.' || c.COLUMN_NAME || ' IS NOT NULL AND :NEW.' || c.COLUMN_NAME || ' IS NULL)'
                 || ' THEN v_cols := v_cols || ''' || c.COLUMN_NAME || ','';  END IF;' || NL;
      END IF;
    END LOOP;

    IF v_old IS NULL THEN
      RAISE_APPLICATION_ERROR(-20100, 'La tabla '||v_tabla||' no existe en el esquema.');
    END IF;

    -- Llave primaria (simple o compuesta)
    FOR k IN (SELECT cc.COLUMN_NAME
                FROM USER_CONSTRAINTS uc
                JOIN USER_CONS_COLUMNS cc ON cc.CONSTRAINT_NAME = uc.CONSTRAINT_NAME
               WHERE uc.TABLE_NAME = v_tabla AND uc.CONSTRAINT_TYPE = 'P'
               ORDER BY cc.POSITION) LOOP
      v_idold := v_idold || CASE WHEN v_idold IS NOT NULL THEN ' || ''-'' || ' END || ':OLD.' || k.COLUMN_NAME;
      v_idnew := v_idnew || CASE WHEN v_idnew IS NOT NULL THEN ' || ''-'' || ' END || ':NEW.' || k.COLUMN_NAME;
    END LOOP;
    IF v_idold IS NULL THEN
      v_idold := 'ROWIDTOCHAR(:OLD.ROWID)';
      v_idnew := 'ROWIDTOCHAR(:NEW.ROWID)';
    END IF;

    v_sql :=
      'CREATE OR REPLACE TRIGGER TRG_AUD_' || SUBSTR(v_tabla, 1, 120) || NL ||
      'AFTER INSERT OR UPDATE OR DELETE ON ' || v_tabla || NL ||
      'FOR EACH ROW' || NL ||
      '-- Trigger generado automaticamente por PKG_AUDITORIA.GENERAR_TRIGGER' || NL ||
      'DECLARE' || NL ||
      '  v_ant  CLOB;' || NL ||
      '  v_nue  CLOB;' || NL ||
      '  v_op   VARCHAR2(6);' || NL ||
      '  v_id   VARCHAR2(100);' || NL ||
      '  v_cols VARCHAR2(4000);' || NL ||
      'BEGIN' || NL ||
      '  IF INSERTING THEN' || NL ||
      '    v_op := ''INSERT'';' || NL ||
      '    v_id := ' || v_idnew || ';' || NL ||
      '    SELECT JSON_OBJECT(' || v_new || ' RETURNING CLOB) INTO v_nue FROM DUAL;' || NL ||
      '  ELSIF UPDATING THEN' || NL ||
      '    v_op := ''UPDATE'';' || NL ||
      '    v_id := ' || v_idnew || ';' || NL ||
      v_cmp ||
      '    IF v_cols IS NULL THEN RETURN; END IF;  -- UPDATE sin cambios reales' || NL ||
      '    SELECT JSON_OBJECT(' || v_old || ' RETURNING CLOB) INTO v_ant FROM DUAL;' || NL ||
      '    SELECT JSON_OBJECT(' || v_new || ' RETURNING CLOB) INTO v_nue FROM DUAL;' || NL ||
      '  ELSE' || NL ||
      '    v_op := ''DELETE'';' || NL ||
      '    v_id := ' || v_idold || ';' || NL ||
      '    SELECT JSON_OBJECT(' || v_old || ' RETURNING CLOB) INTO v_ant FROM DUAL;' || NL ||
      '  END IF;' || NL ||
      '  PKG_AUDITORIA.REGISTRAR(''' || v_tabla || ''', v_op, v_id, v_cols, v_ant, v_nue);' || NL ||
      'END;';
    RETURN v_sql;
  END TEXTO_TRIGGER;

  PROCEDURE GENERAR_TRIGGER (p_tabla IN VARCHAR2) IS
  BEGIN
    IF UPPER(p_tabla) = 'AUDITORIA' THEN
      RAISE_APPLICATION_ERROR(-20101, 'La tabla AUDITORIA no se audita a si misma.');
    END IF;
    EXECUTE IMMEDIATE TEXTO_TRIGGER(p_tabla);
    DBMS_OUTPUT.PUT_LINE('Trigger TRG_AUD_' || UPPER(p_tabla) || ' creado.');
  END GENERAR_TRIGGER;

  PROCEDURE GENERAR_TODOS IS
  BEGIN
    FOR t IN (SELECT TABLE_NAME FROM USER_TABLES
               WHERE TABLE_NAME <> 'AUDITORIA'
                 AND TABLE_NAME NOT LIKE 'BIN$%'
                 AND TABLE_NAME NOT LIKE 'SYS\_%' ESCAPE '\'
                 AND TABLE_NAME NOT LIKE 'DR$%'
                 AND IOT_TYPE IS NULL AND TEMPORARY = 'N'
               ORDER BY TABLE_NAME) LOOP
      GENERAR_TRIGGER(t.TABLE_NAME);
    END LOOP;
  END GENERAR_TODOS;

  PROCEDURE PURGAR (p_antes_de IN DATE) IS
  BEGIN
    g_permitir_purga := TRUE;
    DELETE FROM AUDITORIA WHERE FECHA < CAST(p_antes_de AS TIMESTAMP);
    DBMS_OUTPUT.PUT_LINE(SQL%ROWCOUNT || ' registros de auditoria purgados.');
    g_permitir_purga := FALSE;
  EXCEPTION
    WHEN OTHERS THEN
      g_permitir_purga := FALSE;
      RAISE;
  END PURGAR;

END PKG_AUDITORIA;
/

-- ---------------------------------------------------------------------
-- 3. Proteccion del historial: no se permite editar ni borrar auditoria
-- ---------------------------------------------------------------------
CREATE OR REPLACE TRIGGER TRG_AUDITORIA_PROTEGER
BEFORE UPDATE OR DELETE ON AUDITORIA
FOR EACH ROW
BEGIN
  IF UPDATING OR NOT PKG_AUDITORIA.g_permitir_purga THEN
    RAISE_APPLICATION_ERROR(-20102,
      'Los registros de auditoria no se pueden modificar ni eliminar (use PKG_AUDITORIA.PURGAR).');
  END IF;
END;
/

-- ---------------------------------------------------------------------
-- 4. Generar automaticamente los triggers de auditoria de todas las tablas
-- ---------------------------------------------------------------------
BEGIN
  PKG_AUDITORIA.GENERAR_TODOS;
END;
/

SET LINESIZE 150 PAGESIZE 50
COLUMN TRIGGER_NAME FORMAT A26
COLUMN TABLE_NAME FORMAT A16
COLUMN TRIGGERING_EVENT FORMAT A28
SELECT TRIGGER_NAME, TABLE_NAME, TRIGGERING_EVENT, STATUS
  FROM USER_TRIGGERS
 ORDER BY TABLE_NAME, TRIGGER_NAME;
