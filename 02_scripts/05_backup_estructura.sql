-- =====================================================================
--  Proyecto : Sistema de Reserva de Salas Universitario  (LM_RESERVASALAS)
--  Script   : 05_backup_estructura.sql
--  Objetivo : Respaldo de SOLO LA ESTRUCTURA (sin datos) del esquema.
--  Ejecutar : sqlplus LM_RESERVASALAS/<clave>@localhost:1521/FREEPDB1 @05_backup_estructura.sql <archivo_salida.sql>
--  Resultado: un script .sql con el DDL de tablas, restricciones, indices,
--             comentarios, vistas, paquete y triggers, que recrea la base
--             de datos vacia. Se obtiene con DBMS_METADATA (diccionario).
--  (Alternativa con Data Pump: ver backup_datapump.bat, CONTENT=METADATA_ONLY)
-- =====================================================================
SET ECHO OFF FEEDBACK OFF HEADING OFF VERIFY OFF TERMOUT OFF
SET PAGESIZE 0 LINESIZE 32767 LONG 2000000 LONGCHUNKSIZE 32767
SET TRIMSPOOL ON TRIMOUT ON TAB OFF

BEGIN
  DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'PRETTY',               TRUE);
  DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'SQLTERMINATOR',        TRUE);
  DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'SEGMENT_ATTRIBUTES',   FALSE);
  DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'STORAGE',              FALSE);
  DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'EMIT_SCHEMA',          FALSE);
  DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'REF_CONSTRAINTS',      FALSE);
  DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'CONSTRAINTS_AS_ALTER', FALSE);
END;
/

SPOOL &1

SELECT '-- =====================================================================' || CHR(10) ||
       '--  RESPALDO DE ESTRUCTURA (sin datos) - esquema ' || USER || CHR(10) ||
       '--  Generado: ' || TO_CHAR(SYSDATE, 'YYYY-MM-DD HH24:MI:SS') || CHR(10) ||
       '--  Restaurar: conectado como LM_RESERVASALAS ejecutar @este_archivo.sql' || CHR(10) ||
       '-- =====================================================================' || CHR(10) ||
       'SET DEFINE OFF' || CHR(10) || 'WHENEVER SQLERROR CONTINUE' || CHR(10)
  FROM DUAL;

SELECT CHR(10) || '-- ---------- TABLAS (PK, UNIQUE, CHECK, DEFAULT, IDENTITY) ----------' FROM DUAL;
SELECT DBMS_METADATA.GET_DDL('TABLE', TABLE_NAME)
  FROM USER_TABLES
 WHERE TABLE_NAME NOT LIKE 'BIN$%'
 ORDER BY DECODE(TABLE_NAME, 'FACULTAD',1,'USUARIO',2,'EDIFICIO',3,'TIPO_ESPACIO',4,
                 'ESPACIO',5,'RECURSO',6,'ESPACIO_RECURSO',7,'RESERVA',8,'AUDITORIA',9,99), TABLE_NAME;

SELECT CHR(10) || '-- ---------- LLAVES FORANEAS ----------' FROM DUAL;
SELECT DBMS_METADATA.GET_DDL('REF_CONSTRAINT', CONSTRAINT_NAME)
  FROM USER_CONSTRAINTS
 WHERE CONSTRAINT_TYPE = 'R'
 ORDER BY TABLE_NAME, CONSTRAINT_NAME;

SELECT CHR(10) || '-- ---------- INDICES ----------' FROM DUAL;
SELECT DBMS_METADATA.GET_DDL('INDEX', i.INDEX_NAME)
  FROM USER_INDEXES i
 WHERE i.INDEX_TYPE = 'NORMAL'
   AND NOT EXISTS (SELECT 1 FROM USER_CONSTRAINTS c WHERE c.INDEX_NAME = i.INDEX_NAME)
 ORDER BY i.TABLE_NAME, i.INDEX_NAME;

SELECT CHR(10) || '-- ---------- COMENTARIOS ----------' FROM DUAL;
SELECT DBMS_METADATA.GET_DEPENDENT_DDL('COMMENT', t.TABLE_NAME)
  FROM USER_TABLES t
 WHERE EXISTS (SELECT 1 FROM USER_TAB_COMMENTS c WHERE c.TABLE_NAME = t.TABLE_NAME AND c.COMMENTS IS NOT NULL)
 ORDER BY t.TABLE_NAME;

SELECT CHR(10) || '-- ---------- VISTAS ----------' FROM DUAL;
SELECT DBMS_METADATA.GET_DDL('VIEW', VIEW_NAME) FROM USER_VIEWS ORDER BY VIEW_NAME;

SELECT CHR(10) || '-- ---------- PAQUETES PL/SQL ----------' FROM DUAL;
SELECT DBMS_METADATA.GET_DDL('PACKAGE', OBJECT_NAME)
  FROM USER_OBJECTS WHERE OBJECT_TYPE = 'PACKAGE' ORDER BY OBJECT_NAME;

SELECT CHR(10) || '-- ---------- TRIGGERS (reglas de negocio y auditoria) ----------' FROM DUAL;
SELECT DBMS_METADATA.GET_DDL('TRIGGER', TRIGGER_NAME) FROM USER_TRIGGERS ORDER BY TABLE_NAME, TRIGGER_NAME;

SELECT CHR(10) || '-- Fin del respaldo de estructura' || CHR(10) || 'SELECT OBJECT_TYPE, COUNT(*) FROM USER_OBJECTS GROUP BY OBJECT_TYPE;' FROM DUAL;

SPOOL OFF
SET TERMOUT ON
PROMPT Respaldo de estructura generado en &1
EXIT
