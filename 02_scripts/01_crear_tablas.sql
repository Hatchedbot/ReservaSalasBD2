-- ---------------------------------------------------------------------
-- 1. FACULTAD : dependencias academicas/administrativas de la universidad
-- ---------------------------------------------------------------------
CREATE TABLE FACULTAD (
  ID_FACULTAD   NUMBER(6)      GENERATED BY DEFAULT AS IDENTITY,
  CODIGO        VARCHAR2(10)   NOT NULL,
  NOMBRE        VARCHAR2(100)  NOT NULL,
  DECANO        VARCHAR2(100),
  TELEFONO      VARCHAR2(20),
  CONSTRAINT PK_FACULTAD        PRIMARY KEY (ID_FACULTAD),
  CONSTRAINT UQ_FACULTAD_CODIGO UNIQUE (CODIGO),
  CONSTRAINT UQ_FACULTAD_NOMBRE UNIQUE (NOMBRE),
  CONSTRAINT CK_FACULTAD_CODIGO CHECK (CODIGO = UPPER(CODIGO))
);

-- ---------------------------------------------------------------------
-- 2. USUARIO : estudiantes, profesores, personal y administradores
-- ---------------------------------------------------------------------
CREATE TABLE USUARIO (
  ID_USUARIO     NUMBER(8)      GENERATED BY DEFAULT AS IDENTITY,
  DOCUMENTO      VARCHAR2(15)   NOT NULL,
  NOMBRES        VARCHAR2(60)   NOT NULL,
  APELLIDOS      VARCHAR2(60)   NOT NULL,
  EMAIL          VARCHAR2(120)  NOT NULL,
  TELEFONO       VARCHAR2(20),
  TIPO_USUARIO   VARCHAR2(15)   NOT NULL,
  ID_FACULTAD    NUMBER(6)      NOT NULL,
  ESTADO         VARCHAR2(10)   DEFAULT 'ACTIVO' NOT NULL,
  FECHA_REGISTRO DATE           DEFAULT SYSDATE  NOT NULL,
  CONSTRAINT PK_USUARIO           PRIMARY KEY (ID_USUARIO),
  CONSTRAINT UQ_USUARIO_DOCUMENTO UNIQUE (DOCUMENTO),
  CONSTRAINT UQ_USUARIO_EMAIL     UNIQUE (EMAIL),
  CONSTRAINT CK_USUARIO_EMAIL     CHECK (REGEXP_LIKE(EMAIL, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$')),
  CONSTRAINT CK_USUARIO_DOCUMENTO CHECK (REGEXP_LIKE(DOCUMENTO, '^[0-9]{6,15}$')),
  CONSTRAINT CK_USUARIO_TIPO      CHECK (TIPO_USUARIO IN ('ESTUDIANTE','PROFESOR','PERSONAL','ADMINISTRADOR')),
  CONSTRAINT CK_USUARIO_ESTADO    CHECK (ESTADO IN ('ACTIVO','INACTIVO')),
  CONSTRAINT FK_USUARIO_FACULTAD  FOREIGN KEY (ID_FACULTAD) REFERENCES FACULTAD (ID_FACULTAD)
);
CREATE INDEX IX_USUARIO_FACULTAD ON USUARIO (ID_FACULTAD);

-- ---------------------------------------------------------------------
-- 3. EDIFICIO : bloques del campus con su horario de apertura
-- ---------------------------------------------------------------------
CREATE TABLE EDIFICIO (
  ID_EDIFICIO    NUMBER(6)      GENERATED BY DEFAULT AS IDENTITY,
  CODIGO         VARCHAR2(10)   NOT NULL,
  NOMBRE         VARCHAR2(100)  NOT NULL,
  UBICACION      VARCHAR2(150),
  NUM_PISOS      NUMBER(2)      NOT NULL,
  HORA_APERTURA  NUMBER(2)      DEFAULT 6  NOT NULL,
  HORA_CIERRE    NUMBER(2)      DEFAULT 22 NOT NULL,
  CONSTRAINT PK_EDIFICIO         PRIMARY KEY (ID_EDIFICIO),
  CONSTRAINT UQ_EDIFICIO_CODIGO  UNIQUE (CODIGO),
  CONSTRAINT CK_EDIFICIO_PISOS   CHECK (NUM_PISOS BETWEEN 1 AND 30),
  CONSTRAINT CK_EDIFICIO_HORAS   CHECK (HORA_APERTURA BETWEEN 0 AND 23
                                    AND HORA_CIERRE   BETWEEN 1 AND 24
                                    AND HORA_APERTURA < HORA_CIERRE)
);

-- ---------------------------------------------------------------------
-- 4. TIPO_ESPACIO : aula, sala de estudio, laboratorio, cabina, etc.
-- ---------------------------------------------------------------------
CREATE TABLE TIPO_ESPACIO (
  ID_TIPO              NUMBER(4)      GENERATED BY DEFAULT AS IDENTITY,
  NOMBRE               VARCHAR2(50)   NOT NULL,
  DESCRIPCION          VARCHAR2(200),
  MAX_HORAS            NUMBER(2)      DEFAULT 2   NOT NULL,
  REQUIERE_APROBACION  CHAR(1)        DEFAULT 'N' NOT NULL,
  CONSTRAINT PK_TIPO_ESPACIO        PRIMARY KEY (ID_TIPO),
  CONSTRAINT UQ_TIPO_ESPACIO_NOMBRE UNIQUE (NOMBRE),
  CONSTRAINT CK_TIPO_MAX_HORAS      CHECK (MAX_HORAS BETWEEN 1 AND 12),
  CONSTRAINT CK_TIPO_APROBACION     CHECK (REQUIERE_APROBACION IN ('S','N'))
);

-- ---------------------------------------------------------------------
-- 5. ESPACIO : espacio fisico reservable
-- ---------------------------------------------------------------------
CREATE TABLE ESPACIO (
  ID_ESPACIO   NUMBER(6)      GENERATED BY DEFAULT AS IDENTITY,
  CODIGO       VARCHAR2(15)   NOT NULL,
  NOMBRE       VARCHAR2(100)  NOT NULL,
  ID_EDIFICIO  NUMBER(6)      NOT NULL,
  ID_TIPO      NUMBER(4)      NOT NULL,
  PISO         NUMBER(2)      NOT NULL,
  CAPACIDAD    NUMBER(4)      NOT NULL,
  ESTADO       VARCHAR2(15)   DEFAULT 'DISPONIBLE' NOT NULL,
  CONSTRAINT PK_ESPACIO          PRIMARY KEY (ID_ESPACIO),
  CONSTRAINT UQ_ESPACIO_CODIGO   UNIQUE (CODIGO),
  CONSTRAINT CK_ESPACIO_PISO     CHECK (PISO >= 0),
  CONSTRAINT CK_ESPACIO_CAPACIDAD CHECK (CAPACIDAD BETWEEN 1 AND 1000),
  CONSTRAINT CK_ESPACIO_ESTADO   CHECK (ESTADO IN ('DISPONIBLE','MANTENIMIENTO','INACTIVO')),
  CONSTRAINT FK_ESPACIO_EDIFICIO FOREIGN KEY (ID_EDIFICIO) REFERENCES EDIFICIO (ID_EDIFICIO),
  CONSTRAINT FK_ESPACIO_TIPO     FOREIGN KEY (ID_TIPO)     REFERENCES TIPO_ESPACIO (ID_TIPO)
);
CREATE INDEX IX_ESPACIO_EDIFICIO ON ESPACIO (ID_EDIFICIO);
CREATE INDEX IX_ESPACIO_TIPO     ON ESPACIO (ID_TIPO);

-- ---------------------------------------------------------------------
-- 6. RECURSO : equipamiento (proyector, tablero, computadores, ...)
-- ---------------------------------------------------------------------
CREATE TABLE RECURSO (
  ID_RECURSO   NUMBER(6)      GENERATED BY DEFAULT AS IDENTITY,
  NOMBRE       VARCHAR2(60)   NOT NULL,
  DESCRIPCION  VARCHAR2(200),
  CONSTRAINT PK_RECURSO        PRIMARY KEY (ID_RECURSO),
  CONSTRAINT UQ_RECURSO_NOMBRE UNIQUE (NOMBRE)
);

-- ---------------------------------------------------------------------
-- 7. ESPACIO_RECURSO : recursos con que cuenta cada espacio (N:M)
-- ---------------------------------------------------------------------
CREATE TABLE ESPACIO_RECURSO (
  ID_ESPACIO  NUMBER(6)  NOT NULL,
  ID_RECURSO  NUMBER(6)  NOT NULL,
  CANTIDAD    NUMBER(4)  DEFAULT 1 NOT NULL,
  CONSTRAINT PK_ESPACIO_RECURSO   PRIMARY KEY (ID_ESPACIO, ID_RECURSO),
  CONSTRAINT CK_ESP_REC_CANTIDAD  CHECK (CANTIDAD > 0),
  CONSTRAINT FK_ESP_REC_ESPACIO   FOREIGN KEY (ID_ESPACIO) REFERENCES ESPACIO (ID_ESPACIO) ON DELETE CASCADE,
  CONSTRAINT FK_ESP_REC_RECURSO   FOREIGN KEY (ID_RECURSO) REFERENCES RECURSO (ID_RECURSO)
);
CREATE INDEX IX_ESP_REC_RECURSO ON ESPACIO_RECURSO (ID_RECURSO);

-- ---------------------------------------------------------------------
-- 8. RESERVA : reserva de un espacio por un usuario en una franja horaria
-- ---------------------------------------------------------------------
CREATE TABLE RESERVA (
  ID_RESERVA      NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
  ID_USUARIO      NUMBER(8)      NOT NULL,
  ID_ESPACIO      NUMBER(6)      NOT NULL,
  FECHA_INICIO    DATE           NOT NULL,
  FECHA_FIN       DATE           NOT NULL,
  NUM_ASISTENTES  NUMBER(4)      DEFAULT 1 NOT NULL,
  MOTIVO          VARCHAR2(200)  NOT NULL,
  ESTADO          VARCHAR2(12)   DEFAULT 'PENDIENTE' NOT NULL,
  FECHA_CREACION  DATE           DEFAULT SYSDATE NOT NULL,
  OBSERVACION     VARCHAR2(300),
  CONSTRAINT PK_RESERVA            PRIMARY KEY (ID_RESERVA),
  CONSTRAINT CK_RESERVA_FECHAS     CHECK (FECHA_FIN > FECHA_INICIO),
  CONSTRAINT CK_RESERVA_MISMO_DIA  CHECK (TRUNC(FECHA_INICIO) = TRUNC(FECHA_FIN)),
  CONSTRAINT CK_RESERVA_ASISTENTES CHECK (NUM_ASISTENTES > 0),
  CONSTRAINT CK_RESERVA_ESTADO     CHECK (ESTADO IN ('PENDIENTE','CONFIRMADA','CANCELADA','FINALIZADA')),
  CONSTRAINT FK_RESERVA_USUARIO    FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
  CONSTRAINT FK_RESERVA_ESPACIO    FOREIGN KEY (ID_ESPACIO) REFERENCES ESPACIO (ID_ESPACIO)
);
CREATE INDEX IX_RESERVA_ESPACIO_FECHA ON RESERVA (ID_ESPACIO, FECHA_INICIO);
CREATE INDEX IX_RESERVA_USUARIO       ON RESERVA (ID_USUARIO);

-- ---------------------------------------------------------------------
-- Reglas de negocio de RESERVA (no expresables con CHECK):
--   R1. No puede haber dos reservas activas (PENDIENTE/CONFIRMADA) del
--       mismo espacio con horarios que se crucen  -> evita doble reserva.
--   R2. NUM_ASISTENTES no puede superar la CAPACIDAD del espacio.
--   R3. La duracion no puede superar MAX_HORAS del tipo de espacio.
--   R4. La franja debe estar dentro del horario del edificio.
--   R5. Solo se reservan espacios DISPONIBLES y por usuarios ACTIVOS.
-- Se valida a nivel de SENTENCIA (AFTER ... statement) para evitar el
-- error de tabla mutante ORA-04091 y validar tambien cargas masivas.
-- ---------------------------------------------------------------------
CREATE OR REPLACE TRIGGER TRG_RESERVA_REGLAS
AFTER INSERT OR UPDATE ON RESERVA
DECLARE
  v_id   NUMBER;
BEGIN
  -- R1: cruce de horarios
  SELECT MIN(a.ID_RESERVA) INTO v_id
    FROM RESERVA a
    JOIN RESERVA b
      ON  a.ID_ESPACIO = b.ID_ESPACIO
      AND a.ID_RESERVA < b.ID_RESERVA
      AND a.FECHA_INICIO < b.FECHA_FIN
      AND b.FECHA_INICIO < a.FECHA_FIN
   WHERE a.ESTADO IN ('PENDIENTE','CONFIRMADA')
     AND b.ESTADO IN ('PENDIENTE','CONFIRMADA');
  IF v_id IS NOT NULL THEN
    RAISE_APPLICATION_ERROR(-20001,
      'Doble reserva: el espacio ya esta reservado en ese horario (cruce con la reserva '||v_id||').');
  END IF;

  -- R2: capacidad
  SELECT MIN(r.ID_RESERVA) INTO v_id
    FROM RESERVA r JOIN ESPACIO e ON e.ID_ESPACIO = r.ID_ESPACIO
   WHERE r.NUM_ASISTENTES > e.CAPACIDAD
     AND r.ESTADO IN ('PENDIENTE','CONFIRMADA');
  IF v_id IS NOT NULL THEN
    RAISE_APPLICATION_ERROR(-20002,
      'La reserva '||v_id||' supera la capacidad del espacio.');
  END IF;

  -- R3: duracion maxima segun el tipo de espacio
  SELECT MIN(r.ID_RESERVA) INTO v_id
    FROM RESERVA r
    JOIN ESPACIO e      ON e.ID_ESPACIO = r.ID_ESPACIO
    JOIN TIPO_ESPACIO t ON t.ID_TIPO    = e.ID_TIPO
   WHERE (r.FECHA_FIN - r.FECHA_INICIO) * 24 > t.MAX_HORAS
     AND r.ESTADO IN ('PENDIENTE','CONFIRMADA');
  IF v_id IS NOT NULL THEN
    RAISE_APPLICATION_ERROR(-20003,
      'La reserva '||v_id||' supera el maximo de horas permitido para ese tipo de espacio.');
  END IF;

  -- R4: horario del edificio
  SELECT MIN(r.ID_RESERVA) INTO v_id
    FROM RESERVA r
    JOIN ESPACIO e  ON e.ID_ESPACIO  = r.ID_ESPACIO
    JOIN EDIFICIO d ON d.ID_EDIFICIO = e.ID_EDIFICIO
   WHERE ((r.FECHA_INICIO - TRUNC(r.FECHA_INICIO)) * 24 < d.HORA_APERTURA
       OR (r.FECHA_FIN    - TRUNC(r.FECHA_FIN))    * 24 > d.HORA_CIERRE)
     AND r.ESTADO IN ('PENDIENTE','CONFIRMADA');
  IF v_id IS NOT NULL THEN
    RAISE_APPLICATION_ERROR(-20004,
      'La reserva '||v_id||' esta fuera del horario de apertura del edificio.');
  END IF;

  -- R5: espacio disponible y usuario activo (solo reservas futuras activas)
  SELECT MIN(r.ID_RESERVA) INTO v_id
    FROM RESERVA r
    JOIN ESPACIO e ON e.ID_ESPACIO = r.ID_ESPACIO
    JOIN USUARIO u ON u.ID_USUARIO = r.ID_USUARIO
   WHERE r.ESTADO IN ('PENDIENTE','CONFIRMADA')
     AND r.FECHA_INICIO >= TRUNC(SYSDATE)
     AND (e.ESTADO <> 'DISPONIBLE' OR u.ESTADO <> 'ACTIVO');
  IF v_id IS NOT NULL THEN
    RAISE_APPLICATION_ERROR(-20005,
      'La reserva '||v_id||' usa un espacio no disponible o un usuario inactivo.');
  END IF;
END;
