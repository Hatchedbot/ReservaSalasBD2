CREATE OR REPLACE EDITIONABLE PACKAGE BODY "PKG_AUDITORIA" AS

  -- Inserta el evento. Se ejecuta en la MISMA transaccion del cambio:
  -- si el cambio se deshace (ROLLBACK) su auditoria tambien.
  PROCEDURE REGISTRAR (
    p_tabla     IN VARCHAR2,
    p_operacion IN VARCHAR2,
    p_id        IN VARCHAR2,
    p_columnas  IN VARCHAR2,
    p_anterior  IN CLOB,
    p_nuevo     IN CLOB) IS
  BEGIN
    INSERT INTO AUDITORIA (FECHA, TABLA, OPERACION, ID_REGISTRO, USUARIO_BD,
                           USUARIO_APP, USUARIO_SO, EQUIPO, IP, PROGRAMA,
                           COLUMNAS_MODIFICADAS, DATOS_ANTERIORES, DATOS_NUEVOS)
    VALUES (SYSTIMESTAMP, p_tabla, p_operacion, p_id, USER,
            SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'),
            SYS_CONTEXT('USERENV','OS_USER'),
            SYS_CONTEXT('USERENV','HOST'),
            SYS_CONTEXT('USERENV','IP_ADDRESS'),
            NVL(SYS_CONTEXT('USERENV','MODULE'), SYS_CONTEXT('USERENV','CLIENT_PROGRAM_NAME')),
            RTRIM(p_columnas, ','), p_anterior, p_nuevo);
  END REGISTRAR;

  -- Construye el codigo fuente del trigger de auditoria de una tabla,
  -- leyendo sus columnas y su llave primaria desde el diccionario.
  FUNCTION TEXTO_TRIGGER (p_tabla IN VARCHAR2) RETURN CLOB IS
    v_tabla  VARCHAR2(128) := UPPER(p_tabla);
    v_old    VARCHAR2(32767);
    v_new    VARCHAR2(32767);
    v_cmp    VARCHAR2(32767);
    v_idold  VARCHAR2(4000);
    v_idnew  VARCHAR2(4000);
    v_sql    CLOB;
    NL       CONSTANT VARCHAR2(1) := CHR(10);
  BEGIN
    FOR c IN (SELECT COLUMN_NAME, DATA_TYPE
                FROM USER_TAB_COLUMNS
               WHERE TABLE_NAME = v_tabla
               ORDER BY COLUMN_ID) LOOP
      v_old := v_old || CASE WHEN v_old IS NOT NULL THEN ', ' END
               || '''' || c.COLUMN_NAME || ''' VALUE :OLD.' || c.COLUMN_NAME;
      v_new := v_new || CASE WHEN v_new IS NOT NULL THEN ', ' END
               || '''' || c.COLUMN_NAME || ''' VALUE :NEW.' || c.COLUMN_NAME;
      -- Deteccion de columnas cuyo valor realmente cambio. Se tratan los NULL
      -- explicitamente porque NULL <> valor no es verdadero en SQL.
      IF c.DATA_TYPE NOT IN ('CLOB','BLOB','NCLOB','LONG') THEN
        v_cmp := v_cmp || '    IF (:OLD.' || c.COLUMN_NAME || ' <> :NEW.' || c.COLUMN_NAME || ')'
                 || ' OR (:OLD.' || c.COLUMN_NAME || ' IS NULL AND :NEW.' || c.COLUMN_NAME || ' IS NOT NULL)'
                 || ' OR (:OLD.' || c.COLUMN_NAME || ' IS NOT NULL AND :NEW.' || c.COLUMN_NAME || ' IS NULL)'
                 || ' THEN v_cols := v_cols || ''' || c.COLUMN_NAME || ','';  END IF;' || NL;
      END IF;
    END LOOP;

    IF v_old IS NULL THEN
      RAISE_APPLICATION_ERROR(-20100, 'La tabla '||v_tabla||' no existe en el esquema.');
    END IF;

    -- Llave primaria (simple o compuesta)
    FOR k IN (SELECT cc.COLUMN_NAME
                FROM USER_CONSTRAINTS uc
                JOIN USER_CONS_COLUMNS cc ON cc.CONSTRAINT_NAME = uc.CONSTRAINT_NAME
               WHERE uc.TABLE_NAME = v_tabla AND uc.CONSTRAINT_TYPE = 'P'
               ORDER BY cc.POSITION) LOOP
      v_idold := v_idold || CASE WHEN v_idold IS NOT NULL THEN ' || ''-'' || ' END || ':OLD.' || k.COLUMN_NAME;
      v_idnew := v_idnew || CASE WHEN v_idnew IS NOT NULL THEN ' || ''-'' || ' END || ':NEW.' || k.COLUMN_NAME;
    END LOOP;
    IF v_idold IS NULL THEN
      v_idold := 'ROWIDTOCHAR(:OLD.ROWID)';
      v_idnew := 'ROWIDTOCHAR(:NEW.ROWID)';
    END IF;

    v_sql :=
      'CREATE OR REPLACE TRIGGER TRG_AUD_' || SUBSTR(v_tabla, 1, 120) || NL ||
      'AFTER INSERT OR UPDATE OR DELETE ON ' || v_tabla || NL ||
      'FOR EACH ROW' || NL ||
      '-- Trigger generado automaticamente por PKG_AUDITORIA.GENERAR_TRIGGER' || NL ||
      'DECLARE' || NL ||
      '  v_ant  CLOB;' || NL ||
      '  v_nue  CLOB;' || NL ||
      '  v_op   VARCHAR2(6);' || NL ||
      '  v_id   VARCHAR2(100);' || NL ||
      '  v_cols VARCHAR2(4000);' || NL ||
      'BEGIN' || NL ||
      '  IF INSERTING THEN' || NL ||
      '    v_op := ''INSERT'';' || NL ||
      '    v_id := ' || v_idnew || ';' || NL ||
      '    SELECT JSON_OBJECT(' || v_new || ' RETURNING CLOB) INTO v_nue FROM DUAL;' || NL ||
      '  ELSIF UPDATING THEN' || NL ||
      '    v_op := ''UPDATE'';' || NL ||
      '    v_id := ' || v_idnew || ';' || NL ||
      v_cmp ||
      '    IF v_cols IS NULL THEN RETURN; END IF;  -- UPDATE sin cambios reales' || NL ||
      '    SELECT JSON_OBJECT(' || v_old || ' RETURNING CLOB) INTO v_ant FROM DUAL;' || NL ||
      '    SELECT JSON_OBJECT(' || v_new || ' RETURNING CLOB) INTO v_nue FROM DUAL;' || NL ||
      '  ELSE' || NL ||
      '    v_op := ''DELETE'';' || NL ||
      '    v_id := ' || v_idold || ';' || NL ||
      '    SELECT JSON_OBJECT(' || v_old || ' RETURNING CLOB) INTO v_ant FROM DUAL;' || NL ||
      '  END IF;' || NL ||
      '  PKG_AUDITORIA.REGISTRAR(''' || v_tabla || ''', v_op, v_id, v_cols, v_ant, v_nue);' || NL ||
      'END;';
    RETURN v_sql;
  END TEXTO_TRIGGER;

  PROCEDURE GENERAR_TRIGGER (p_tabla IN VARCHAR2) IS
  BEGIN
    IF UPPER(p_tabla) = 'AUDITORIA' THEN
      RAISE_APPLICATION_ERROR(-20101, 'La tabla AUDITORIA no se audita a si misma.');
    END IF;
    EXECUTE IMMEDIATE TEXTO_TRIGGER(p_tabla);
    DBMS_OUTPUT.PUT_LINE('Trigger TRG_AUD_' || UPPER(p_tabla) || ' creado.');
  END GENERAR_TRIGGER;

  PROCEDURE GENERAR_TODOS IS
  BEGIN
    FOR t IN (SELECT TABLE_NAME FROM USER_TABLES
               WHERE TABLE_NAME <> 'AUDITORIA'
                 AND TABLE_NAME NOT LIKE 'BIN$%'
                 AND TABLE_NAME NOT LIKE 'SYS\_%' ESCAPE '\'
                 AND TABLE_NAME NOT LIKE 'DR$%'
                 AND IOT_TYPE IS NULL AND TEMPORARY = 'N'
               ORDER BY TABLE_NAME) LOOP
      GENERAR_TRIGGER(t.TABLE_NAME);
    END LOOP;
  END GENERAR_TODOS;

  PROCEDURE PURGAR (p_antes_de IN DATE) IS
  BEGIN
    g_permitir_purga := TRUE;
    DELETE FROM AUDITORIA WHERE FECHA < CAST(p_antes_de AS TIMESTAMP);
    DBMS_OUTPUT.PUT_LINE(SQL%ROWCOUNT || ' registros de auditoria purgados.');
    g_permitir_purga := FALSE;
  EXCEPTION
    WHEN OTHERS THEN
      g_permitir_purga := FALSE;
      RAISE;
  END PURGAR;

END PKG_AUDITORIA;
