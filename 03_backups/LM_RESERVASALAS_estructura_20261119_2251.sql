  CREATE OR REPLACE FORCE EDITIONABLE VIEW "VW_AUDITORIA" ("ID_AUDITORIA", "FECHA", "FECHA_HORA", "DIA", "TABLA", "OPERACION", "ID_REGISTRO", "QUIEN", "USUARIO_BD", "USUARIO_APP", "USUARIO_SO", "EQUIPO", "IP", "PROGRAMA", "COLUMNAS_MODIFICADAS", "DATOS_ANTERIORES", "DATOS_NUEVOS") AS
  SELECT a.ID_AUDITORIA,
       CAST(a.FECHA AS DATE)                         AS FECHA,
       TO_CHAR(a.FECHA, 'YYYY-MM-DD HH24:MI:SS.FF3') AS FECHA_HORA,
       TRUNC(CAST(a.FECHA AS DATE))                  AS DIA,
       a.TABLA,
       a.OPERACION,
       a.ID_REGISTRO,
       NVL(a.USUARIO_APP, a.USUARIO_BD)              AS QUIEN,
       a.USUARIO_BD,
       a.USUARIO_APP,
       a.USUARIO_SO,
       a.EQUIPO,
       a.IP,
       a.PROGRAMA,
       a.COLUMNAS_MODIFICADAS,
       a.DATOS_ANTERIORES,
       a.DATOS_NUEVOS
  FROM AUDITORIA a;


  CREATE OR REPLACE FORCE EDITIONABLE VIEW "VW_AUDITORIA_RESUMEN" ("DIA", "TABLA", "INSERCIONES", "ACTUALIZACIONES", "ELIMINACIONES", "TOTAL") AS
  SELECT TRUNC(CAST(FECHA AS DATE)) AS DIA,
       TABLA,
       COUNT(CASE WHEN OPERACION = 'INSERT' THEN 1 END) AS INSERCIONES,
       COUNT(CASE WHEN OPERACION = 'UPDATE' THEN 1 END) AS ACTUALIZACIONES,
       COUNT(CASE WHEN OPERACION = 'DELETE' THEN 1 END) AS ELIMINACIONES,
       COUNT(*)                                         AS TOTAL
  FROM AUDITORIA
 GROUP BY TRUNC(CAST(FECHA AS DATE)), TABLA;


